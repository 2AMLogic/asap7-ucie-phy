#!/usr/bin/env python3
"""Source of the drawn TX/RX cell netlists (stdlib only; run as `python3 -I`).

The four cells are written here as device-level topology on ASAP7 RVT FinFETs
and rendered to design/netlist/*.sp. Port names and widths are the drawn-cell
boundary of rtl/README.md (spec section 4): per lane `tx_a[1:0]`, `tx_b[1:0]`
in on the TX cell, `rx_a[1:0]`, `rx_b[1:0]` out on the RX cell. The clock lane
uses the two clock cells (spec section 1: 17 lane cells per direction).

This is topology only. It is not simulated here (spec/decisions/0003), carries
no sizing optimisation and implies no rate or performance. Device names and
the w = 27 nm x nfin convention follow the pinned ASAP7 CDL (spec/asap7-bringup.md).

    gen_cells.py            write design/netlist/*.sp
    gen_cells.py --check    exit 0 if the committed files match, 3 if they drift
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "netlist"
FIN_W_NM = 27


class Cell:
    def __init__(self, name, ports, doc):
        self.name, self.ports, self.doc = name, ports, doc
        self.lines = []
        self.n = 0

    def _dev(self, kind, d, g, s, nfin):
        self.n += 1
        bulk = "VSS" if kind == "nmos_rvt" else "VDD"
        self.lines.append(
            f"M{self.n} {d} {g} {s} {bulk} {kind} l=20n w={FIN_W_NM * nfin}n nfin={nfin}")

    def inv(self, a, y, nfin=3):
        self._dev("nmos_rvt", y, a, "VSS", nfin)
        self._dev("pmos_rvt", y, a, "VDD", nfin)

    def nand2(self, a, b, y, nfin=3):
        mid = f"n{self.n}"
        self._dev("nmos_rvt", y, a, mid, nfin)
        self._dev("nmos_rvt", mid, b, "VSS", nfin)
        self._dev("pmos_rvt", y, a, "VDD", nfin)
        self._dev("pmos_rvt", y, b, "VDD", nfin)

    def tgate(self, a, y, g, gb, nfin=3):
        """Transmission gate a<->y, conducting when g=1, gb=0."""
        self._dev("nmos_rvt", y, g, a, nfin)
        self._dev("pmos_rvt", y, gb, a, nfin)

    def mux2(self, d0, d1, sel, selb, y, nfin=3):
        """2:1 mux: y follows d0 when sel=0, d1 when sel=1 (selb = ~sel)."""
        self.tgate(d0, y, selb, sel, nfin)
        self.tgate(d1, y, sel, selb, nfin)

    def latch(self, d, ph, phb, q, tag, nfin=2):
        """Pass gate into a cross-coupled inverter pair, transparent on ph=1."""
        self.tgate(d, f"{tag}_x", ph, phb, nfin)
        self.inv(f"{tag}_x", f"{tag}_xb", nfin)
        self.inv(f"{tag}_xb", q, nfin)
        self.inv(f"{tag}_xb", f"{tag}_xk", 1)
        self.tgate(f"{tag}_xk", f"{tag}_x", phb, ph, 1)

    def render(self):
        head = [f"* {self.name}: {self.doc}",
                "* Generated by design/gen_cells.py; do not edit by hand.",
                f".subckt {self.name} {' '.join(self.ports)} VDD VSS"]
        return "\n".join(head + self.lines + [".ends", ""])


def tx_cell():
    c = Cell("tx_cell",
             ["tx_a[0]", "tx_a[1]", "tx_b[0]", "tx_b[1]", "sel1", "sel2", "pad"],
             "last 2:1 stages and output driver of one TX lane")
    c.inv("sel1", "sel1b")
    c.inv("sel2", "sel2b")
    # stage 1: each stream's two bits to one serial bit (a: d0 then d2; b: d1 then d3)
    c.mux2("tx_a[0]", "tx_a[1]", "sel1", "sel1b", "sa")
    c.mux2("tx_b[0]", "tx_b[1]", "sel1", "sel1b", "sb")
    # stage 2: interleave the two streams
    c.mux2("sa", "sb", "sel2", "sel2b", "m")
    # driver: three-stage inverter chain, tapered
    c.inv("m", "d1", 3)
    c.inv("d1", "d2", 6)
    c.inv("d2", "pad", 12)
    return c


def rx_cell():
    c = Cell("rx_cell",
             ["pad", "ph[0]", "ph[1]", "ph[2]", "ph[3]",
              "rx_a[0]", "rx_a[1]", "rx_b[0]", "rx_b[1]"],
             "input stage and sampler of one RX lane")
    # input stage: two inverters
    c.inv("pad", "i1", 3)
    c.inv("i1", "i2", 6)
    # sampler: one latch per phase; order d0,d1,d2,d3 -> a[0],b[0],a[1],b[1]
    for k, q in enumerate(["rx_a[0]", "rx_b[0]", "rx_a[1]", "rx_b[1]"]):
        c.inv(f"ph[{k}]", f"phb{k}", 1)
        c.latch("i2", f"ph[{k}]", f"phb{k}", q, f"s{k}")
    return c


def tx_clk_cell():
    c = Cell("tx_clk_cell", ["clk", "fwd_en", "pad"],
             "forwarded-clock lane: gate (tx_fwd_en) and driver")
    c.nand2("clk", "fwd_en", "g", 3)
    c.inv("g", "d1", 3)
    c.inv("d1", "d2", 6)
    c.inv("d2", "pad", 12)
    return c


def rx_clk_cell():
    c = Cell("rx_clk_cell", ["pad", "rx_clk"],
             "forwarded-clock lane: input stage to rx_clk")
    c.inv("pad", "i1", 3)
    c.inv("i1", "i2", 6)
    c.inv("i2", "i3", 6)
    c.inv("i3", "rx_clk", 12)
    return c


CELLS = [tx_cell, rx_cell, tx_clk_cell, rx_clk_cell]


def main(argv):
    check = "--check" in argv
    drift = 0
    for make in CELLS:
        cell = make()
        path = OUT / f"{cell.name}.sp"
        text = cell.render()
        if check:
            if not path.is_file() or path.read_text() != text:
                print(f"drifted: {path}", file=sys.stderr)
                drift += 1
        else:
            OUT.mkdir(exist_ok=True)
            path.write_text(text)
    return 3 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
