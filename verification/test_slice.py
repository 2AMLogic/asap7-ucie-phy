"""cocotb testbench for rtl/slice.v.

TX boundary -> behavioural model of the drawn stages -> RX boundary, with the
forwarded clock generated by the model at a deliberate frequency and phase
offset from the parallel clock. Times are simulator units only; nothing here
is a rate or timing claim (spec section 2: rate is an STA statement).

The behavioural drawn-stage model lives here and never under rtl/.
"""
import json
import os
import random
from collections import deque

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import FallingEdge, RisingEdge, Timer

LANES = int(os.environ.get("LANES", "16"))
NEG = os.environ.get("NEG_CONTROL", "0") == "1"
CLK_PS = 10000


class Link:
    """Drawn-stage model: captures boundary words, replays them on a forwarded
    clock of different period and phase. The clock only toggles per word."""

    def __init__(self, dut, rx_period_ps, phase_ps):
        self.dut, self.period, self.phase = dut, rx_period_ps, phase_ps
        self.q = deque()
        self.epoch = 0
        self.words_sent = 0

    def flush(self):
        self.q.clear()
        self.epoch += 1

    async def capture(self):
        dut = self.dut
        while True:
            await FallingEdge(dut.clk)
            if int(dut.rst_n.value) and int(dut.tx_fwd_en.value):
                self.q.append((int(dut.tx_a.value), int(dut.tx_b.value)))

    async def replay(self):
        dut = self.dut
        dut.rx_clk.value = 0
        dut.rx_a.value = 0
        dut.rx_b.value = 0
        while True:
            if not self.q:
                await Timer(self.period // 4, unit="ps")
                continue
            epoch = self.epoch
            a, b = self.q.popleft()
            dut.rx_a.value, dut.rx_b.value = a, b
            await Timer(self.period // 4, unit="ps")
            if epoch != self.epoch:
                continue
            dut.rx_clk.value = 1
            self.words_sent += 1
            await Timer(self.period // 2, unit="ps")
            dut.rx_clk.value = 0
            await Timer(self.period // 4, unit="ps")


class Bench:
    def __init__(self, dut, rng, rx_period_ps, phase_ps):
        self.dut, self.rng = dut, rng
        self.link = Link(dut, rx_period_ps, phase_ps)
        self.expected = deque()
        self.accepted = 0
        self.received = 0
        self.errors = []
        self.in_reset = False
        self.p_valid = 0.7
        self.p_ready = 0.7
        self.cur = None
        self.lr_p1 = 0  # link_ready driven after the previous edge
        self.lr_p2 = 0  # ... and the edge before

    def err(self, msg):
        self.errors.append(msg)
        self.dut._log.error(msg)

    async def drive_and_check(self):
        dut = self.dut
        while True:
            await RisingEdge(dut.clk)
            # sample pre-edge values
            if int(dut.rst_n.value) == 0:
                if any(v.value.is_resolvable and int(v.value) for v in (dut.tx_ready, dut.rx_valid)):
                    self.err("tx_ready/rx_valid high during reset")
                dut.tx_valid.value = 0
                dut.link_ready.value = 0
                self.cur = None
                self.lr_p1 = self.lr_p2 = 0
                continue
            ready = int(dut.tx_ready.value)
            if ready != self.lr_p2:
                self.err("tx_ready is not the registered link_ready")
            valid = int(dut.tx_valid.value)
            if valid and ready:
                self.expected.append(self.cur)
                self.accepted += 1
                self.cur = None
            if int(dut.rx_valid.value):
                got = int(dut.rx_data.value)
                if not self.expected:
                    self.err("RX valid with nothing outstanding (spurious/duplicate)")
                else:
                    want = self.expected.popleft()
                    if NEG:
                        want ^= 1  # deliberately broken check
                    if got != want:
                        self.err(f"negative control: word mismatch {got:#x} != {want:#x}"
                                 if NEG else f"word mismatch {got:#x} != {want:#x}")
                    self.received += 1
            if int(dut.rx_overflow.value):
                self.err("rx_overflow set")
            # next drive
            if self.cur is None and self.rng.random() < self.p_valid:
                self.cur = self.rng.getrandbits(4 * LANES)
            if self.cur is not None:
                dut.tx_valid.value = 1
                dut.tx_data.value = self.cur
            else:
                dut.tx_valid.value = 0
                dut.tx_data.value = self.rng.getrandbits(4 * LANES)  # must be ignored
            lr = int(self.rng.random() < self.p_ready)
            dut.link_ready.value = lr
            self.lr_p2, self.lr_p1 = self.lr_p1, lr

    async def fwd_en_check(self):
        """tx_fwd_en must be high exactly one cycle after each accepted word."""
        dut = self.dut
        while True:
            await RisingEdge(dut.clk)
            acc = int(dut.rst_n.value) and int(dut.tx_valid.value) and int(dut.tx_ready.value)
            await FallingEdge(dut.clk)
            if int(dut.rst_n.value) and int(dut.tx_fwd_en.value) != acc:
                self.err("tx_fwd_en does not match accepted word")

    async def reset(self, cycles=4):
        dut = self.dut
        dut.rst_n.value = 0
        dut.rx_rst_n.value = 0
        await Timer(cycles * CLK_PS, unit="ps")
        self.link.flush()
        self.expected.clear()
        self.cur = None
        await Timer(CLK_PS // 3, unit="ps")
        dut.rst_n.value = 1
        dut.rx_rst_n.value = 1
        await RisingEdge(dut.clk)

    async def run_cycles(self, n):
        for _ in range(n):
            await RisingEdge(self.dut.clk)

    async def drain(self):
        self.p_valid = 0.0
        await self.run_cycles(60)
        if self.cur is not None:
            # a held word may still be waiting for ready
            self.p_ready = 1.0
            await self.run_cycles(60)


TOTALS = {"words_checked": 0, "resets": 0, "scenarios": 0}


async def scenario(dut, period, phase):
    seed = int(os.environ["SEED"])
    rng = random.Random(seed ^ period)
    dut.tx_valid.value = 0
    dut.tx_data.value = 0
    dut.link_ready.value = 0
    dut.rst_n.value = 0
    dut.rx_rst_n.value = 0
    dut.rx_clk.value = 0
    cocotb.start_soon(Clock(dut.clk, CLK_PS, unit="ps").start())

    b = Bench(dut, rng, period, phase)
    cocotb.start_soon(b.link.capture())
    cocotb.start_soon(b.link.replay())
    cocotb.start_soon(b.drive_and_check())
    cocotb.start_soon(b.fwd_en_check())
    await b.reset()
    # full-rate bursts, random stalls, long valid-low runs, ready-starved
    for p_valid, p_ready, cycles in [(1.0, 1.0, 32), (0.7, 0.7, 400), (0.05, 0.9, 300), (1.0, 0.3, 200)]:
        b.p_valid, b.p_ready = p_valid, p_ready
        await b.run_cycles(cycles)
        b.p_valid = 0.0
        await b.run_cycles(40)
    # reset mid-stream while words are in flight
    b.p_valid, b.p_ready = 1.0, 1.0
    await b.run_cycles(25)
    pre = b.received
    await b.reset()
    TOTALS["resets"] += 1
    b.p_valid, b.p_ready = 0.8, 0.8
    await b.run_cycles(200)
    await b.drain()
    if b.expected:
        b.err(f"{len(b.expected)} accepted word(s) never arrived")
    TOTALS["words_checked"] += pre + b.received
    TOTALS["scenarios"] += 1
    dut._log.info(f"rx period {period} phase {phase}: {pre} words before reset, "
                  f"{b.received} after (clk period {CLK_PS})")
    with open(os.environ["SUMMARY_PATH"], "w") as f:
        json.dump({"lanes": LANES, "seed": int(os.environ["SEED"]), "negative_control": NEG, **TOTALS}, f)
    assert b.received > 100, "too few words moved to be meaningful"
    assert not b.errors, "; ".join(b.errors[:5])


@cocotb.test()
async def loopback_rx_faster(dut):
    await scenario(dut, 9300, 2700)


@cocotb.test()
async def loopback_rx_slower(dut):
    await scenario(dut, 10700, 6100)


@cocotb.test()
async def loopback_rx_close(dut):
    await scenario(dut, 9900, 1300)
